// Algunos errores de validación y permiso traen un motivo con mensaje propio
export function errorMessage(code, details) {
  const reason = details?.reason;
  if (reason && labels.admin.reasons[reason]) return labels.admin.reasons[reason];
  return errorLabels[code] ?? errorLabels.UNKNOWN;
}

export function validationMessage(code) {
  return labels.validation[code] ?? errorLabels.UNKNOWN;
}
